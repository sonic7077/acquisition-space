import {test,expect} from '@playwright/test';

test('评论双标签整理需求，原话、透明评分与写手上下文关联',async({page,request})=>{
  await request.post('/api/auth/login',{data:{username:'admin',password:'admin'}});
  const team=await(await request.post('/api/teams',{data:{name:'需求验收组'}})).json();
  const ip=await(await request.post('/api/ips',{data:{name:'需求验收IP',team_id:team.id}})).json();
  const lead=await(await request.post('/api/records/leads',{data:{ip_id:ip.id,title:'咨询用户',body:'家庭预算多少钱？',contactable:false,platform:'抖音',platform_comment_id:'e2e-'+Date.now()}})).json();
  await request.post('/api/records/leads',{data:{ip_id:ip.id,title:'质疑用户',body:'家庭预算都是骗人，智商税',contactable:false}});
  let writer=await(await request.post('/api/writers',{data:{ip_id:ip.id,name:'需求关联写手',answers:['顾问','家庭','咨询','待核实','预算','不承诺','无','直说','无','你','1000','视频号']}})).json();
  writer=await(await request.post(`/api/writers/${writer.id}/compile`,{data:{version:writer.version}})).json();
  writer=await(await request.post(`/api/writers/${writer.id}/activate`,{data:{version:writer.version}})).json();
  await page.goto('/');await page.getByRole('button',{name:'进入工作台'}).click();
  await page.getByRole('button',{name:'需求库',exact:true}).click();
  await page.getByLabel('需求目标IP',{exact:true}).selectOption(ip.id);
  await page.getByRole('button',{name:'新增主题',exact:true}).click();
  const topic=page.getByRole('dialog',{name:'新增需求主题'});
  await topic.getByLabel('主题名称',{exact:true}).fill('家庭预算');
  await topic.getByLabel('主题关键词',{exact:true}).fill('预算,咨询');
  await topic.getByRole('button',{name:'保存主题',exact:true}).click();
  await page.getByRole('button',{name:'从评论整理需求',exact:true}).click();
  const card=page.locator('.demand-item').filter({hasText:'家庭预算'});
  await expect(card).toContainText('有效需求 1');await expect(card).toContainText('优先级 3');await expect(card).toContainText('反对/共鸣研究 1');
  await card.getByText('查看原话与来源',{exact:true}).click();await expect(card).toContainText(lead.body);
  await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.screenshot({path:'/tmp/huoke-demands-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1050});await page.screenshot({path:'/tmp/huoke-demands.png',fullPage:true});
  const createdDraft=page.waitForResponse(r=>r.url().endsWith('/api/drafts')&&r.request().method()==='POST');
  await card.getByRole('button',{name:'转选题',exact:true}).click();
  expect((await createdDraft).ok()).toBeTruthy();
  const drafts=await(await request.get('/api/drafts')).json();const draft=drafts.find((d:any)=>d.ip_id===ip.id&&d.need_id);expect(draft.demand_snapshot.quotes[0].body).toBe(lead.body);
  await page.getByRole('button',{name:'审稿',exact:true}).click();await page.locator('.draft-item').filter({hasText:draft.id.slice(0,8)}).click();
  await page.getByRole('button',{name:'用写手改编',exact:true}).click();const rewrite=page.getByRole('dialog',{name:'用写手改编'});
  await rewrite.getByLabel('专属写手',{exact:true}).selectOption(writer.id);
  await rewrite.getByLabel('改编文体',{exact:true}).selectOption('original-video-writer');
  await expect(rewrite.getByLabel('关联需求',{exact:true})).toHaveValue(draft.need_id);
  await rewrite.getByRole('button',{name:'预览改编上下文',exact:true}).click();
  await expect(rewrite.getByLabel('改编提示包',{exact:true})).toContainText('家庭预算多少钱？');
  await rewrite.getByRole('button',{name:'关闭',exact:true}).click();
  await page.getByRole('button',{name:'IP与写手',exact:true}).click();
  await page.getByLabel('目标IP',{exact:true}).selectOption(ip.id);
  await page.getByText('写作与分析',{exact:true}).click();
  const writing=page.locator('.card').filter({has:page.getByRole('heading',{name:'创建内容任务',exact:true})});
  await writing.getByLabel('关联需求（可选）',{exact:true}).selectOption(draft.need_id);
  await writing.getByLabel('内容主题与要求',{exact:true}).fill('回答咨询费用问题');
  await writing.getByRole('button',{name:'生成上下文预览',exact:true}).click();
  await expect(page.getByLabel('写作上下文预览',{exact:true})).toContainText('家庭预算多少钱？');
  await page.getByRole('button',{name:'客户线索',exact:true}).click();
  await page.getByLabel('评论类型筛选',{exact:true}).selectOption('追问');
  const entry=page.locator(`[data-lead-id="${lead.id}"]`);await expect(entry).toBeVisible();await expect(entry).toContainText('问价格');
  await entry.getByRole('button',{name:'查看 / 编辑',exact:true}).click();const edit=page.getByRole('dialog',{name:'编辑线索'});
  await edit.getByLabel('评论类型',{exact:true}).selectOption('反对');await edit.getByLabel('客户意向',{exact:true}).selectOption('无关');
  await edit.getByRole('button',{name:'保存线索',exact:true}).click();
  await page.getByRole('button',{name:'本地重分析评论',exact:true}).click();
  const updated=(await(await request.get('/api/records/leads')).json()).find((l:any)=>l.id===lead.id);expect(updated.intent).toBe('无关');expect(updated.content_type).toBe('反对');
});
