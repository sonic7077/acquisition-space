import {test,expect} from '@playwright/test';

test('知识目录树、强制末级导入、预览目的地、目录移动与检索',async({page,request})=>{
  await request.post('/api/auth/login',{data:{username:'admin',password:'admin'}});
  await page.route('**/api/ips', route => route.fulfill({json:[]}));
  await page.goto('/');await page.getByRole('button',{name:'进入工作台'}).click();await page.getByRole('button',{name:'知识库',exact:true}).click();
  await expect(page.getByLabel('目标IP',{exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'上传文件 / ZIP',exact:true})).toBeDisabled();
  await page.locator('.kb-directory-branch>summary>button').filter({hasText:'2-产品库'}).click();
  await expect(page.getByLabel('导入末级目录',{exact:true})).toHaveValue('');
  await expect(page.getByRole('button',{name:'上传知识库目录',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'目录 2-产品库/重疾险',exact:true}).click();
  await expect(page.getByLabel('导入末级目录',{exact:true})).toHaveValue('product-critical-illness');
  await expect(page.getByRole('button',{name:'上传文件 / ZIP',exact:true})).toBeEnabled();
  const chooser=page.waitForEvent('filechooser');await page.getByRole('button',{name:'上传文件 / ZIP',exact:true}).click();
  const previewRequest=page.waitForRequest(r=>r.url().endsWith('/api/knowledge/preview'));
  await(await chooser).setFiles({name:'保障说明.md',mimeType:'text/markdown',buffer:Buffer.from('重疾险保障责任必须核对实际合同条款。')});
  expect((await previewRequest).postData()).not.toContain('name="ip_id"');
  const modal=page.getByRole('dialog',{name:'确认知识库导入'});
  await expect(modal).toContainText('2-产品库/重疾险');
  await expect(modal).not.toContainText('所属IP');
  await modal.getByRole('button',{name:'确认导入',exact:true}).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByRole('table').getByText('保障说明',{exact:true})).toBeVisible();
  await expect(page.getByRole('columnheader',{name:'IP',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'查看内容',exact:true}).click();
  await page.getByRole('button',{name:'核验通过',exact:true}).click();
  await page.getByRole('button',{name:'查看内容',exact:true}).click();
  await page.getByLabel('调整归档末级目录',{exact:true}).selectOption('product-savings');
  await page.getByRole('button',{name:'更新归档目录',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('归档目录：2-产品库/储蓄险');
  await expect(page.getByRole('dialog').getByText('已核验',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  await expect(page.getByRole('table').getByText('保障说明',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'目录 2-产品库/储蓄险',exact:true}).click();
  await expect(page.getByRole('table').getByText('保障说明',{exact:true})).toBeVisible();
  await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'/tmp/acquisition-knowledge-directories.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  expect((await page.locator('.kb-directory-tree').boundingBox())!.width).toBeGreaterThan(250);
  await page.screenshot({path:'/tmp/acquisition-knowledge-directories-mobile.png',fullPage:true});
});
