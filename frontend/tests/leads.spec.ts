  const authors=[{id:'author-dy',title:'同名博主',platform:'抖音',ip_id:null},{id:'author-xhs',title:'同名博主',platform:'小红书',ip_id:ip.id}];
  const works=[{id:'work-a',title:'方案怎么选',author_id:'author-dy',platform:'抖音',ip_id:null},{id:'work-b',title:'收费说明',author_id:'author-dy',platform:'抖音',ip_id:null},{id:'work-c',title:'小红书笔记',author_id:'author-xhs',platform:'小红书',ip_id:ip.id}];
