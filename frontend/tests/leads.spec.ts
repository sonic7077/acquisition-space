  await page.route('**/api/records/leads/lead-1',async r=>{edit=r.request().postDataJSON();await r.fulfill({json:{...leads[0],...edit}})});
  await page.goto('/');await page.getByRole('button',{name:'进入工作台'}).click();await page.getByRole('button',{name:'客户线索',exact:true}).click();
  await expect(page.getByRole('heading',{name:'来源博主与客户线索',exact:true})).toBeVisible();
  await expect(page.locator('.lead-author')).toHaveCount(4);
  const dy=page.locator('.lead-author[data-author-id="author-dy"]');
  const xhs=page.locator('.lead-author[data-author-id="author-xhs"]');
  await expect(dy).toContainText('2 条记录');await expect(xhs).toContainText('1 条记录');
  await page.getByRole('button',{name:'展开全部',exact:true}).click();
  await expect(dy.getByText('评论甲',{exact:true})).toBeVisible();
  await expect(dy.getByText('评论乙',{exact:true})).toBeVisible();
  await expect(xhs.getByText('评论甲',{exact:true})).toHaveCount(0);
  await expect(page.getByText('电话咨询',{exact:true})).toBeVisible();
  await page.getByLabel('搜索记录').fill('方案怎么选');
  await expect(page.locator('.lead-author')).toHaveCount(1);
  await expect(page.getByText('评论甲',{exact:true})).toBeVisible();
  await expect(page.getByText('评论乙',{exact:true})).toHaveCount(0);
  await page.getByLabel('搜索记录').fill('');
  await page.getByLabel('线索类型').selectOption('contactable');
  await expect(page.getByText('电话咨询',{exact:true})).toBeVisible();
  await expect(page.getByText('评论甲',{exact:true})).toHaveCount(0);
  await page.getByLabel('线索类型').selectOption('all');
  await page.getByRole('button',{name:'展开全部',exact:true}).click();
  await page.locator('.lead-entry[data-lead-id="lead-1"]').getByRole('button',{name:'查看 / 编辑',exact:true}).click();
  await expect(page.getByRole('dialog').getByLabel('目标IP',{exact:true})).toHaveValue('未归属IP');
  await page.getByRole('dialog').getByLabel('负责人').fill('跟进人员');
  await page.getByRole('button',{name:'保存线索',exact:true}).click();
  await expect.poll(()=>edit?.owner).toBe('跟进人员');
  await expect(page.getByRole('dialog')).not.toBeVisible();
